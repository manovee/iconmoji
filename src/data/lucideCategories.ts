let cdnCategoriesCache: LucideCategory[] | null = null;
let cdnFetchPromise: Promise<LucideCategory[]> | null = null;

const NORMALIZED_TO_ICON_NAME = new Map<string, LucideIconName>();
for (const name of LUCIDE_ICON_NAMES) {
  NORMALIZED_TO_ICON_NAME.set(name.toLowerCase().replace(/-/g, ""), name);
}

export function parseCdnCategories(data: unknown): LucideCategory[] | null {
  if (!data || typeof data !== "object") return null;

  if (Array.isArray(data)) {
    return data as LucideCategory[];
  }

  const categoryMap = new Map<string, Set<string>>();
  for (const def of CATEGORY_DEFINITIONS) {
    categoryMap.set(def.label, new Set());
  }
  const generalIcons = new Set<string>();

  const tagToCategory = new Map<string, string>();
  for (const def of CATEGORY_DEFINITIONS) {
    for (const tag of def.tags) {
      tagToCategory.set(tag.toLowerCase(), def.label);
    }
  }

  for (const [key, value] of Object.entries(data as Record<string, unknown>)) {
    const iconCandidate = NORMALIZED_TO_ICON_NAME.get(key.toLowerCase().replace(/-/g, ""));
    if (iconCandidate && Array.isArray(value)) {
      let placed = false;
      for (const tag of value) {
        const catLabel = tagToCategory.get(String(tag).toLowerCase());
        if (catLabel && categoryMap.has(catLabel)) {
          categoryMap.get(catLabel)!.add(iconCandidate);
          placed = true;
          break;
        }
      }
      if (!placed) {
        generalIcons.add(iconCandidate);
      }
    } else if (Array.isArray(value)) {
      const catLabel = tagToCategory.get(key.toLowerCase()) || key;
      if (!categoryMap.has(catLabel)) {
        categoryMap.set(catLabel, new Set());
      }
      for (const iconItem of value) {
        const iconName = NORMALIZED_TO_ICON_NAME.get(String(iconItem).toLowerCase().replace(/-/g, ""));
        if (iconName) {
          categoryMap.get(catLabel)!.add(iconName);
        }
      }
    }
  }

  const result: LucideCategory[] = [];
  for (const [label, iconsSet] of categoryMap.entries()) {
    if (iconsSet.size > 0) {
      result.push({
        label,
        icons: Array.from(iconsSet).sort()
      });
    }
  }
  if (generalIcons.size > 0) {
    result.push({
      label: "General",
      icons: Array.from(generalIcons).sort()
    });
  }
  return result.length > 0 ? result : null;
}

export async function fetchLucideCategories(
  url: string = LUCIDE_CATEGORIES_CDN_URL
): Promise<LucideCategory[]> {
  if (cdnCategoriesCache) {
    return cdnCategoriesCache;
  }
  if (cdnFetchPromise) {
    return cdnFetchPromise;
  }

  cdnFetchPromise = (async () => {
    try {
      if (typeof fetch === "undefined") {
        return BASE_LUCIDE_CATEGORIES;
      }
      const response = await fetch(url);
      if (!response.ok) {
        return BASE_LUCIDE_CATEGORIES;
      }
      const json = await response.json();
      const parsed = parseCdnCategories(json);
      if (parsed && parsed.length > 0) {
        cdnCategoriesCache = parsed;
        return parsed;
      }
    } catch {
      // Offline or network error: gracefully fall back to BASE_LUCIDE_CATEGORIES
    }
    return BASE_LUCIDE_CATEGORIES;
  })();

  return cdnFetchPromise;
}

export function filterLucideCategories(
  query: string,
  iconNames?: string[],
  categories: LucideCategory[] = BASE_LUCIDE_CATEGORIES
): LucideCategory[] {
  const allowedSet = iconNames?.length ? new Set(iconNames) : null;
  const filteredIcons = filterLucideIcons(query, iconNames);
  const matchingSet = new Set(filteredIcons);

  const result: LucideCategory[] = [];
  const assigned = new Set<string>();

  for (const cat of categories) {
    const matchedIcons = cat.icons.filter((icon) => {
      if (allowedSet && !allowedSet.has(icon)) return false;
      return matchingSet.has(icon as LucideIconName);
    });

    if (matchedIcons.length > 0) {
      result.push({
        label: cat.label,
        icons: matchedIcons
      });
      for (const icon of matchedIcons) {
        assigned.add(icon);
      }
    }
  }

  const leftover = filteredIcons.filter((icon) => !assigned.has(icon));
  if (leftover.length > 0) {
    result.push({
      label: "Other",
      icons: leftover
    });
  }

  return result;
}
